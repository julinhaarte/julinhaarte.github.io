document.addEventListener('DOMContentLoaded', function() {
    let currentLang = 'pt-BR';
    const languageButtons = document.querySelectorAll('.language-option');
    const translatableNodes = document.querySelectorAll('[data-i18n]');
    const placeholderNodes = document.querySelectorAll('[data-i18n-placeholder]');
    const altNodes = document.querySelectorAll('[data-i18n-alt]');
    const ariaLabelNodes = document.querySelectorAll('[data-i18n-aria-label]');

    function getTranslation(key) {
        return translations[currentLang][key] || translations['pt-BR'][key] || '';
    }

    function applyLanguage(lang) {
        currentLang = translations[lang] ? lang : 'pt-BR';
        document.documentElement.lang = currentLang;

        translatableNodes.forEach(function(node) {
            const key = node.dataset.i18n;
            node.textContent = getTranslation(key);
        });

        placeholderNodes.forEach(function(node) {
            const key = node.dataset.i18nPlaceholder;
            node.placeholder = getTranslation(key);
        });

        altNodes.forEach(function(node) {
            const key = node.dataset.i18nAlt;
            node.alt = getTranslation(key);
        });

        ariaLabelNodes.forEach(function(node) {
            const key = node.dataset.i18nAriaLabel;
            node.setAttribute('aria-label', getTranslation(key));
        });

        languageButtons.forEach(function(button) {
            const isActive = button.dataset.lang === currentLang;
            button.classList.toggle('active', isActive);
            button.setAttribute('aria-pressed', String(isActive));
        });
    }

    languageButtons.forEach(function(button) {
        button.addEventListener('click', function() {
            applyLanguage(button.dataset.lang);
        });
    });

    emailjs.init('SM_xuvN0sBrOJni4v');

    document.getElementById('emailForm').addEventListener('submit', function(event) {
        event.preventDefault();

        const emailParams = {
            email: document.getElementById('email').value,
            message: document.getElementById('message').value
        };

        emailjs.send('service_d9pm57j', 'template_0o0sstm', emailParams)
            .then(function() {
                alert(getTranslation('emailSuccess'));
            }, function() {
                alert(getTranslation('emailError'));
            });
    });

    applyLanguage('pt-BR');
});